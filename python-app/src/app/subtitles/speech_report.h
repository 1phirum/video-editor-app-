#pragma once

// What went wrong with a generated voiceover, in a form a dialog can show.
//
// Two questions, asked of the timeline rather than of the worker's output, so the
// answers survive a save and reopen: which voices play on top of another voice,
// and which ones would have had to be spoken faster than natural to fit the room
// before the next line. The second list is the one to act on - a voice is only on
// A2 because it ran long, and running long is what requiredSpeed measures.
//
// Own file, not Backend: this is a read-only pass over the clip list with no state
// of its own, and Backend is already five thousand lines.

#include <QString>
#include <QVariantList>
#include <QVariantMap>

namespace cutpro::speech {

// Rows handed to the dialog, per section. A 20000-cue film with everything
// overlapping would otherwise build a list model with 20000 delegates in it, on
// the GUI thread, to say something the first few hundred rows and the counts
// already say. Counts are always exact; the rows are the worst offenders.
constexpr int kSpeechReportRowLimit = 400;

// The speed histogram the rebuild bar reads. A cap is only worth choosing if you can
// see what it leaves behind, and "how many lines need more than 1.4x" cannot be
// answered from the capped row lists - the counts there stop at 400. So every voice
// clip that needs more room than it has is counted into a bucket by its requiredSpeed,
// and the dialog sums the buckets from a candidate cap upward to say how many lines
// will still overlap at it.
//
// Bucket i holds the clips whose requiredSpeed falls in
//   (kSpeedBucketBase + i*kSpeedBucketStep, kSpeedBucketBase + (i+1)*kSpeedBucketStep]
// and the last bucket also absorbs everything beyond its top. A clip that already fits
// at its natural pace (requiredSpeed <= kSpeedBucketBase) is in no bucket at all, so
// for a cap of base + k*step the count of lines that still will not fit is exactly the
// sum of buckets k and up - including k = 0, which is the natural-pace case.
//
// 0.05 steps from 1.00 to 4.00, which is 60 ints for a project of any size.
constexpr double kSpeedBucketBase = 1.0;
constexpr double kSpeedBucketStep = 0.05;
constexpr int kSpeedBucketCount = 60;

// Above this a line does not just fit, it sounds hurried. Used only to warn - the cap
// is the user's call and a rushed line is still better than a lost one for some jobs.
constexpr double kRushedSpeed = 1.3;

// Reads the whole clip list, looks only at clips generated by text_to_speech.
//
// Returns:
//   voiceClips      int    generated voice clips found
//   trackCount      int    distinct audio tracks they occupy
//   tracks          list   those track names, A-order ("A1", "A2", ...)
//   overlapCount    int    voice clips that play while another voice plays
//   fastCount       int    voice clips whose requiredSpeed is above kFastSpeed
//   maxRequiredSpeed double worst requiredSpeed in the sequence
//   retimedCount    int    clips a previous run sped up (ttsSpeed != 1.0)
//   rushedCount     int    of those, ones above kRushedSpeed
//   appliedSpeed    double the cap that produced this timeline, as far as the clips
//                          show it: the worst ttsSpeed on any of them, 1.0 if none
//   speedBuckets    list   kSpeedBucketCount ints, counts by requiredSpeed
//   speedBucketBase double first bucket's lower bound
//   speedBucketStep double bucket width
//   rushedSpeed     double kRushedSpeed
//   rowLimit        int    kSpeechReportRowLimit, so the dialog can say "first N"
//   overlaps        list   up to rowLimit maps, worst overlap first
//   fast            list   up to rowLimit maps, worst requiredSpeed first
//
// Every row carries clipId, index, track, startMs, endMs, durationMs, audioMs,
// slotMs, speed, requiredSpeed and text. An overlap row adds otherClipId,
// otherTrack, otherStartMs, otherEndMs, overlapMs and concurrent (how many voices
// are audible at once at that point).
QVariantMap buildSpeechReport(const QVariantList &clips);

} // namespace cutpro::speech
